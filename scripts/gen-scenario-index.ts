/**
 * Regenerates src/model/data/scenarios/index.ts from the scenario files in
 * that directory, so adding a scenario is just adding a file that exports
 * `scenario`. Run automatically by `npm run model:verify`.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const dir = resolve(process.cwd(), 'src/model/data/scenarios');
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts' && !f.endsWith('.test.ts'))
  .sort();
const ident = (f: string) => f.replace(/\.ts$/, '').replace(/[^A-Za-z0-9]+(.)?/g, (_, c: string | undefined) => (c ? c.toUpperCase() : ''));

const out = `// GENERATED by scripts/gen-scenario-index.ts — one import per file in this directory.
import type { ModelSlice } from '../../types';
${files.map((f) => `import { scenario as ${ident(f)} } from './${f.replace(/\.ts$/, '')}';`).join('\n')}

export const slice: ModelSlice = { scenarios: [${files.map(ident).join(', ')}] };
`;
writeFileSync(resolve(dir, 'index.ts'), out);
console.log(`scenarios/index.ts: ${files.length} scenarios`);
