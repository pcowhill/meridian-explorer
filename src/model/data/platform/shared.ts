/** A `(typeof X)[number]` union type derived from an enum-like tuple. */
function unionType(id: string, name: string, constId: string, constName: string, file: string, line: number, tags: string[]): Entity {
  const [parent] = id.split('#');
  return {
    id,
    kind: 'type',
    name,
    parent,
    detail: 5,
    summary: `The union of the literal values in \`${constName}\`.`,
    signature: `export type ${name} = (typeof ${constName})[number]`,
    tags,
    sources: [src(file, line, line, `export type ${name}`)],
    description: `Derived from the tuple, so adding a value to \`${constName}\` (${constId}) widens this type everywhere it is used.`,
  };
}

