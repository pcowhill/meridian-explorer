const authGuard = (source: FlowStep['source']): FlowStep => ({
  kind: 'guard',
  target: 'be:auth/guards#requireAuth',
  label: 'requireAuth',
  detail: 'Resolves the session cookie to a user and sets `req.user`. No role is required — authorisation happens per account inside the service.',
  rejects: [
    { status: 401, code: 'unauthenticated', when: 'No session cookie.' },
    { status: 401, code: 'session_expired', when: 'The session token is unknown or expired (the dead cookie is cleared).' },
  ],
  source,
});

const rateGuard = (bucket: 'cards' | 'risk', source: FlowStep['source']): FlowStep => ({
  kind: 'guard',
  target: 'be:abuse/rate-limit#rateLimit',
  label: `rateLimit('${bucket}')`,
  detail:
    bucket === 'cards'
      ? 'Public-demo mode only: one per-user bucket shared by all six card mutations — 30 requests per 5 minutes.'
      : 'Public-demo mode only: one per-user bucket shared by disputes and fraud responses (and joint invitations) — 20 requests per 5 minutes.',
  rejects: [{ status: 429, code: 'rate_limited', when: `Public-demo mode and the user exceeded the \`${bucket}\` bucket (reply carries Retry-After).` }],
  source,
});

