/** An enum-like `as const` tuple plus the union type derived from it (two exported names, two ids). */
function enumPair(opts: {
  file: string;
  moduleId: string;
  constName: string;
  typeName: string;
  line: number;
  summary: string;
  values: { value: string; meaning?: string }[];
  tags: string[];
  docStart?: number;
  detail?: Entity['detail'];
}): Entity[] {
  const start = opts.docStart ?? opts.line;
  return [
    {
      id: `${opts.moduleId}#${opts.constName}`,
      kind: 'constant',
      name: opts.constName,
      parent: opts.moduleId,
      summary: opts.summary,
      description: `An \`as const\` tuple; the union type \`${opts.typeName}\` is derived from it on the next line, so the list of allowed values exists exactly once. SQLite has no enums, so the column that stores one of these is a plain string.`,
      values: opts.values,
      tags: opts.tags,
      aliases: [opts.typeName],
      detail: opts.detail,
      sources: [s(opts.file, start, opts.line + 1, opts.constName)],
    },
    {
      id: `${opts.moduleId}#${opts.typeName}`,
      kind: 'type',
      name: opts.typeName,
      parent: opts.moduleId,
      summary: `Union type of the values in \`${opts.constName}\`: ${opts.values.map((v) => `\`${v.value}\``).join(' | ')}.`,
      values: opts.values,
      tags: opts.tags,
      aliases: [opts.constName],
      detail: opts.detail,
      sources: [s(opts.file, opts.line + 1, opts.line + 1, `export type ${opts.typeName}`)],
    },
  ];
}

